#!/usr/bin/env python3
"""Extract the ffmpeg fixture matrices of the craft-{h264,hevc,vp8,vp9} test suites into
src/matrix_data.rs, so the oracle harness generates exactly the streams the crates' own
conformance tests use. Usage: extract_matrix.py <craft-libs checkout> > src/matrix_data.rs"""
import re, sys, pathlib

root = pathlib.Path(sys.argv[1])

def split_top(s, sep=','):
    out, depth, cur, i, instr = [], 0, '', 0, False
    while i < len(s):
        c = s[i]
        if instr:
            cur += c
            if c == '\\': cur += s[i+1]; i += 1
            elif c == '"': instr = False
        elif c == '"': instr = True; cur += c
        elif c in '([{': depth += 1; cur += c
        elif c in ')]}': depth -= 1; cur += c
        elif c == sep and depth == 0: out.append(cur.strip()); cur = ''
        else: cur += c
        i += 1
    if cur.strip(): out.append(cur.strip())
    return out

def strip_comments(s):
    return re.sub(r'//[^\n]*', '', s)

def consts(src):
    d = {}
    for m in re.finditer(r'const (\w+): &str = ("(?:[^"\\]|\\.)*");', src):
        d[m.group(1)] = m.group(2)
    return d

def val(tok, c):
    tok = tok.strip()
    return c.get(tok, tok)

def strlist(tok, c):
    tok = tok.strip()
    if tok.startswith('&'): tok = tok[1:]
    assert tok[0] == '[' and tok[-1] == ']', tok
    return [val(t, c) for t in split_top(tok[1:-1])]

def section(src):
    i = src.index('pub const FIXTURES')
    j = src.index('= &[', i) + 4
    depth, k = 1, j
    instr = False
    while depth:
        ch = src[k]
        if instr:
            if ch == '\\': k += 1
            elif ch == '"': instr = False
        elif ch == '"': instr = True
        elif ch == '[': depth += 1
        elif ch == ']': depth -= 1
        k += 1
    return src[j:k-1]

def entries(codec):
    path = root / f'crates/{codec}/tests/it/common/mod.rs'
    src = strip_comments(path.read_text())
    c = consts(src)
    body = section(src)
    rows = []
    for item in split_top(body):
        if item.startswith('fx!('):
            a = split_top(item[4:-1])
            if codec == 'hevc':   # name src w h n filter bd [args]
                name, srcn, w, h, n, flt, bd, args = a
                pix = 'yuv420p10le' if val(bd, c) == '10' else 'yuv420p'
                rows.append((codec, name, srcn, w, h, n, flt, f'"{pix}"', args))
            elif codec == 'vp8':  # name src w h n [args]
                name, srcn, w, h, n, args = a
                rows.append((codec, name, srcn, w, h, n, '""', '"yuv420p"', args))
            elif codec == 'vp9':  # name src w h n filter pix [args]
                name, srcn, w, h, n, flt, pf, args = a
                rows.append((codec, name, srcn, w, h, n, flt, pf, args))
        else:
            assert item.startswith('Fixture {'), item[:40]
            kv = {}
            for f in split_top(item[len('Fixture {'):-1]):
                k, v = f.split(':', 1)
                kv[k.strip()] = v.strip()
            rows.append((codec, kv['name'], kv['source'], kv['width'], kv['height'], kv['frames'], kv['filter'], '"yuv420p"', kv['args']))
    out = []
    for (codec, name, srcn, w, h, n, flt, pf, args) in rows:
        al = strlist(args, c)
        out.append(f'    Fx {{ codec: "{codec}", name: {val(name,c)}, source: {val(srcn,c)}, w: {w}, h: {h}, frames: {n}, filter: {val(flt,c)}, pix_fmt: {val(pf,c)}, args: &[{", ".join(al)}] }},')
    return out

print('// @generated by scripts/extract_matrix.py from the craft-{h264,hevc,vp8,vp9} tests/it/common/mod.rs fixture tables.')
print('// Do not edit by hand; rerun the script against the checkout the oracle is built from.')
print('#![cfg_attr(rustfmt, rustfmt::skip)]')
print('use crate::matrix::Fx;')
print('pub const FIXTURES: &[Fx] = &[')
for codec in ['h264', 'hevc', 'vp8', 'vp9']:
    print('\n'.join(entries(codec)))
print('];')
