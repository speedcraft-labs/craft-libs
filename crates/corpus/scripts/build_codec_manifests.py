#!/usr/bin/env python3
"""Build pinned craft-corpus manifests for the codec conformance suites (ticket #195).

Run:  python3 -I crates/corpus/scripts/build_codec_manifests.py [h264|hevc|vp8|vp9|av1 ...]

Sources (all HTTPS):
  h264  fate-suite.ffmpeg.org/h264-conformance/ (+ FRext/): the JVT/ITU-T H.264.1 conformance bitstreams.
  hevc  fate-suite.ffmpeg.org/hevc-conformance/: the JCT-VC (ITU-T H.265.1) conformance bitstreams.
  vp8   storage.googleapis.com/downloads.webmproject.org/test_data/libvpx/vp80-*.ivf + .md5
  vp9   same bucket, vp90/91/92/93-*.webm + .md5
  av1   storage.googleapis.com/aom-test-data/av1-1-*.ivf (+ .md5, and .mkv/.obu variants where listed)

The libvpx / libaom file names come from the bucket listings. Every file is downloaded into memory,
hashed, and the manifest written to crates/corpus/manifests/conformance-<codec>.toml. Nothing else is written.
"""
import concurrent.futures as cf, hashlib, html.parser, json, os, re, shutil, sys, urllib.parse, urllib.request
import xml.etree.ElementTree as ET

MANIFEST_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "manifests")

FATE = "https://fate-suite.ffmpeg.org/"
VPX = "https://storage.googleapis.com/downloads.webmproject.org/test_data/libvpx/"
AOM = "https://storage.googleapis.com/aom-test-data/"

H264_LICENCE = ("ITU-T H.264.1 / JVT conformance bitstream, published by the Joint Video Team for conformance testing "
                "(no licence text accompanies the files; redistributed unchanged by the FFmpeg FATE suite)")
HEVC_LICENCE = ("ITU-T H.265.1 / JCT-VC conformance bitstream, published by JCT-VC for conformance testing "
                "(no licence text accompanies the files; redistributed unchanged by the FFmpeg FATE suite)")
H264_PROV = ("JVT-site draft_conformance bitstreams (https://www.itu.int/wftp3/av-arch/jvt-site/draft_conformance/, HTTPS but zipped with "
             "multi-MB reference YUVs and a ~250 KB/s mirror) as unpacked by FFmpeg's FATE suite: ")
HEVC_PROV = ("JCT-VC bitstream_exchange/draft_conformance bitstreams (https://www.itu.int/wftp3/av-arch/jctvc-site/bitstream_exchange/draft_conformance/, "
             "zipped) as unpacked by FFmpeg's FATE suite: ")


def get(url):
    req = urllib.request.Request(url, headers={"User-Agent": "craft-corpus-builder"})
    for attempt in range(4):
        try:
            with urllib.request.urlopen(req, timeout=120) as r:
                return r.read()
        except urllib.error.HTTPError as e:
            if e.code == 404:
                return None
            if attempt == 3:
                raise
        except Exception:
            if attempt == 3:
                raise
    return None


class Links(html.parser.HTMLParser):
    def __init__(self):
        super().__init__()
        self.hrefs = []

    def handle_starttag(self, tag, attrs):
        if tag == "a":
            self.hrefs.append(dict(attrs).get("href", ""))


def fate_list(sub):
    p = Links()
    p.feed(get(FATE + sub).decode())
    return sorted(h for h in p.hrefs if h and not h.startswith(("?", "/")) and not h.endswith("/") and h != "md5sum")


def bucket_list(base, prefix):
    names, token = [], None
    while True:
        if "webmproject" in base:
            u = "https://storage.googleapis.com/downloads.webmproject.org/?prefix=" + urllib.parse.quote(prefix) + "&max-keys=1000"
        else:
            u = "https://storage.googleapis.com/aom-test-data/?prefix=" + urllib.parse.quote(prefix) + "&max-keys=1000"
        if token:
            u += "&marker=" + urllib.parse.quote(token)
        xml = ET.fromstring(get(u))
        ns = {"s": xml.tag.split("}")[0][1:]}
        keys = [k.text for k in xml.findall("s:Contents/s:Key", ns)]
        names += keys
        if xml.findtext("s:IsTruncated", namespaces=ns) != "true" or not keys:
            return names
        token = keys[-1]


def q(s):
    return json.dumps(s, ensure_ascii=False)


def fetch_hash(item):
    path, url, tmp = item
    data = get(url)
    if data is None:
        return path, None, 0
    return path, hashlib.sha256(data).hexdigest(), len(data)


def write(name, description, header, files, licence, provenance_of, tags_of):
    """files: [(dest_path, url)]; writes manifests/conformance-<name>.toml."""
    with cf.ThreadPoolExecutor(8) as ex:
        res = list(ex.map(fetch_hash, [(p, u, None) for p, u in files]))
    missing = [p for p, h, _ in res if h is None]
    total = sum(n for _, h, n in res if h)
    out = [f"# Generated by crates/corpus/scripts/build_codec_manifests.py -- do not edit by hand.", *["# " + l for l in header],
           f"# Missing upstream (404, left out): {', '.join(missing) if missing else 'none'}", "",
           f'name = "conformance-{name}"', f"description = {q(description)}", ""]
    urls = dict(files)
    for p, h, n in res:
        if h is None:
            continue
        out += ["[[file]]", f"path = {q(p)}", f"url = {q(urls[p])}", f'sha256 = "{h}"', f"licence = {q(licence)}",
                f"provenance = {q(provenance_of(p))}", f"tags = {json.dumps(tags_of(p))}", ""]
    with open(os.path.join(MANIFEST_DIR, f"conformance-{name}.toml"), "w") as f:
        f.write("\n".join(out))
    print(f"{name}: {len(res) - len(missing)} files, {total / 1e6:.1f} MB, missing {missing}")


def build_h264():
    top = [("", n) for n in fate_list("h264-conformance/")]
    fr = [("FRext/", n) for n in fate_list("h264-conformance/FRext/")]
    files = [(sub + n, f"{FATE}h264-conformance/{sub}{n}") for sub, n in top + fr]
    write("h264", "H.264 JVT conformance bitstreams (baseline, main, extended, FRExt): the H.264.1 suite as mirrored by FFmpeg FATE.",
          [f"Source: {FATE}h264-conformance/ (served over HTTPS; the official ITU site is HTTPS too but ships zips with YUVs at ~250 KB/s).",
           "Reference output: none ships with the FATE copy; crates/conformance/expected/h264.tsv pins per-stream MD5s of the ffmpeg decode."],
          files, H264_LICENCE, lambda p: H264_PROV + p,
          lambda p: ["frext"] if p.startswith("FRext/") else ["avcv1"])


def build_hevc():
    names = [n for n in fate_list("hevc-conformance/") if not n.startswith(("MVHEVCS", "SHVC"))]
    files = [(n, f"{FATE}hevc-conformance/{n}") for n in names]
    write("hevc", "HEVC JCT-VC conformance bitstreams (version 1 and RExt): the H.265.1 suite as mirrored by FFmpeg FATE.",
          [f"Source: {FATE}hevc-conformance/ (HTTPS). Multi-layer MV-HEVC bitstreams (MVHEVCS_*) are left out: layers > 0 are not decoded.",
           "Reference output: none ships with the FATE copy; crates/conformance/expected/hevc.tsv pins per-stream MD5s of the ffmpeg decode."],
          files, HEVC_LICENCE, lambda p: HEVC_PROV + p,
          lambda p: ["rext"] if "RExt" in p or "Main_422" in p or "444" in p else ["v1"])


def libvpx(codec, prefix, exts):
    keys = [k.split("/")[-1] for k in bucket_list(VPX, "test_data/libvpx/" + prefix)]
    have = set(keys)
    # A vector without a published .md5 has no reference output: leave it out.
    names = sorted(k for k in keys if k.endswith(exts) and k + ".md5" in have)
    files = []
    for n in names:
        files += [(n, VPX + n), (n + ".md5", VPX + n + ".md5")]
    return names, files


LIBVPX_LICENCE = "BSD-3-Clause (libvpx test vectors, The WebM Project Authors; see https://github.com/webmproject/libvpx/blob/main/LICENSE)"
LIBVPX_PROV = "libvpx test vector, as published by the WebM project: "


def build_vp8():
    names, files = libvpx("vp8", "vp80-", (".ivf",))
    write("vp8", "libvpx VP8 test vectors vp80-00..05 with their per-frame I420 MD5 files.",
          [f"Source: {VPX} (HTTPS). The .md5 files hold one 'md5  name-WxH-NNNN.i420' line per frame."],
          files, LIBVPX_LICENCE, lambda p: LIBVPX_PROV + p, lambda p: ["md5"] if p.endswith(".md5") else ["vp8"])


def build_vp9():
    names, files = [], []
    for pre in ("vp90-2-", "vp91-2-", "vp92-2-", "vp93-2-"):
        n, f = libvpx("vp9", pre, (".webm",))
        names += n
        files += f
    prof = lambda p: ["md5"] if p.endswith(".md5") else ["profile" + p[3]]
    write("vp9", "libvpx VP9 test vectors vp90/91/92/93-2-* (profiles 0 to 3) with their per-frame MD5 files.",
          [f"Source: {VPX} (HTTPS). Profile 1/2/3 vectors are the vp91/vp92/vp93 files.",
           "Per-frame MD5s cover the display-size planes in the stream's native format (16-bit little-endian samples above 8 bit)."],
          files, LIBVPX_LICENCE, lambda p: LIBVPX_PROV + p, prof)


def build_av1():
    keys = [k for k in bucket_list(AOM, "av1-1-")]
    names = sorted(k for k in keys if k.endswith((".ivf", ".mkv", ".obu")) and not k.endswith(".md5"))
    have = set(keys)
    files = []
    for n in names:
        files.append((n, AOM + n))
        if n + ".md5" in have:
            files.append((n + ".md5", AOM + n + ".md5"))
    write("av1", "libaom AV1 test vectors av1-1-* (8 and 10 bit, annexb and section 5 streams) with their per-frame MD5 files.",
          [f"Source: {AOM} (HTTPS; the libaom test-vector bucket). Argon AV1 conformance streams are NOT included: they are a commercial product",
           "(Argon Design) distributed under licence and registration, so they cannot be fetched anonymously."],
          files, "BSD-2-Clause-Patent (libaom test vectors, Alliance for Open Media; see https://aomedia.googlesource.com/aom/+/refs/heads/main/LICENSE)",
          lambda p: "libaom test vector, as published by AOMedia: " + p,
          lambda p: ["md5"] if p.endswith(".md5") else ["b10" if "-b10-" in p else "b8"])


BUILDERS = dict(h264=build_h264, hevc=build_hevc, vp8=build_vp8, vp9=build_vp9, av1=build_av1)

if __name__ == "__main__":
    for k in sys.argv[1:] or list(BUILDERS):
        BUILDERS[k]()
